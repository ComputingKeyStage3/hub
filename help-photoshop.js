/* ===================================================================
   help-photoshop.js — what the Photoshop helper knows.

   The answers teach the way the Year 7 and Year 8 Digital Graphics
   lessons (7.2 and 8.2) teach it: the same tools, the same keys and the
   same menus as the slides and help sheets. A student who is told one
   way in the lesson and another way here does not know which to trust,
   so where Photoshop has three ways of doing something, this says the
   one the lesson showed. Undo is Ctrl + Alt + Z for the same reason.

   Tools the lessons do not use still have an answer, for a student who
   asks for one by name, but a short one, and where a lesson tool does
   the same job the answer says that instead.

   The entries also follow the department's R094 tutorial numbers (card),
   so "tutorial 12" still finds an answer. The cue cards themselves are
   not copied here: anything in this folder is published to the open web.

   Every entry is one answer:
     id     never changes; feedback and links use it
     title  what the student sees as the heading
     ask    ways a student might ask for it, in their own words. This is
            what the matching is mostly done against, so add to it freely
            whenever a question was missed.
     tool   the tool and its key, shown as a badge
     steps  what to do, in order. Short: one action a line.
     fix    "Still not working?" reasons, most likely first
     see    other entries worth offering next
     card   the R094 tutorial number, where there is one
     cards  other tutorial numbers the same answer covers

   No em dashes in anything a student reads.
   =================================================================== */
